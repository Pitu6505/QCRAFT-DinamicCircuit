@dataclass
class CaseResult:
    case_id: str
    algorithm: str
    level: str
    qubits: int
    status: str
    detail: str
    original_qubits: int = 0
    compressed_qubits: int = 0
    original_depth: int = 0
    compressed_depth: int = 0
    original_gates: int = 0
    compressed_gates: int = 0


def parse_csv_items(raw: str) -> List[str]:
    return [item.strip() for item in raw.split(",") if item.strip()]


def sanitize_filename(value: str) -> str:
    return re.sub(r"[^a-zA-Z0-9_.-]+", "_", value).strip("_")


def ensure_non_variational_algorithms(algorithms: List[str]) -> None:
    forbidden = sorted([a for a in algorithms if a.lower() in FORBIDDEN_VARIATIONAL_ALGORITHMS])
    if forbidden:
        raise ValueError(
            "Variational circuits are disabled in this script. Remove these algorithms: "
            + ", ".join(forbidden)
        )


SCHEDULER_FRIENDLY_GATES = {
    "id", "x", "y", "z", "h", "s", "sdg", "t", "tdg", "sx", "sxdg",
    "p", "rx", "ry", "rz", "u", "u1", "u2", "u3",
    "cx", "cy", "cz", "ch", "ecr", "swap", "iswap", "cswap", "ccx",
    "cp", "crx", "cry", "crz", "cu", "rxx", "ryy", "rzz", "rzx",
    "reset",
}


def _format_param(param: object) -> str:
    if isinstance(param, float):
        return repr(param)
    if isinstance(param, int):
        return str(param)
    return str(param)


def _to_qcraft_python(circuit, case_id: str) -> str:
    # Expand custom/composite instructions (like gate_Oracle) to scheduler-friendly operations.
    expanded = circuit.decompose(reps=10)

    lines: List[str] = [
        "from qiskit import QuantumRegister, ClassicalRegister, QuantumCircuit",
        "",
        f"qreg_q = QuantumRegister({expanded.num_qubits}, 'q')",
        f"creg_c = ClassicalRegister({expanded.num_clbits}, 'c')",
        "circuit = QuantumCircuit(qreg_q, creg_c)",
        "",
    ]

    for instruction in expanded.data:
        op = instruction.operation
        name = op.name
        q_indices = [expanded.find_bit(q).index for q in instruction.qubits]
        c_indices = [expanded.find_bit(c).index for c in instruction.clbits]

        if name == "measure":
            if len(q_indices) != 1 or len(c_indices) != 1:
                raise ValueError(f"Unsupported measure shape for {case_id}: q={q_indices}, c={c_indices}")
            lines.append(f"circuit.measure(qreg_q[{q_indices[0]}], creg_c[{c_indices[0]}])")
            continue

        if name == "barrier":
            args = ", ".join(f"qreg_q[{idx}]" for idx in q_indices)
            lines.append(f"circuit.barrier({args})")
            continue

        if name == "delay":
            if len(q_indices) != 1:
                raise ValueError(f"Unsupported delay shape for {case_id}: q={q_indices}")
            duration = getattr(op, "duration", None)
            unit = getattr(op, "unit", "dt")
            if duration is None:
                raise ValueError(f"Delay duration missing for {case_id}")
            lines.append(f"circuit.delay({duration}, qreg_q[{q_indices[0]}], unit='{unit}')")
            continue

        if name not in SCHEDULER_FRIENDLY_GATES:
            raise ValueError(
                f"Unsupported op for scheduler-friendly export in {case_id}: {name}. "
                "Use alg/indep or extend SCHEDULER_FRIENDLY_GATES."
            )

        params = [_format_param(param) for param in op.params]
        qargs = [f"qreg_q[{idx}]" for idx in q_indices]
        args = ", ".join(params + qargs)
        lines.append(f"circuit.{name}({args})")

    lines.extend([
        "",
        "# Optional: print(circuit)",
    ])
    return "\n".join(lines) + "\n"


def load_mqt_bench_components():
    try:
        bench_module = importlib.import_module("mqt.bench")
        targets_module = importlib.import_module("mqt.bench.targets")

        BenchmarkLevel = getattr(bench_module, "BenchmarkLevel")
        get_benchmark = getattr(bench_module, "get_benchmark")
        get_device = getattr(targets_module, "get_device")
        get_target_for_gateset = getattr(targets_module, "get_target_for_gateset")
    except Exception as exc:
        raise RuntimeError(
            "mqt.bench is not installed or failed to import. Install it with: pip install mqt.bench"
        ) from exc

    return BenchmarkLevel, get_benchmark, get_device, get_target_for_gateset


def resolve_level(level_name: str, benchmark_level_enum):
    mapping = {
        "alg": benchmark_level_enum.ALG,
        "indep": benchmark_level_enum.INDEP,
        "nativegates": benchmark_level_enum.NATIVEGATES,
        "mapped": benchmark_level_enum.MAPPED,
    }
    if level_name not in mapping:
        raise ValueError(f"Unsupported level: {level_name}")
    return mapping[level_name]


def build_target_for_case(
    level_name: str,
    qubits: int,
    get_device,
    get_target_for_gateset,
    mapped_target: Optional[str],
    native_gateset: Optional[str],
):
    if level_name == "mapped":
        if not mapped_target:
            raise ValueError("Level 'mapped' requires --mapped-target")
        return get_device(mapped_target)

    if level_name == "nativegates":
        if not native_gateset:
            raise ValueError("Level 'nativegates' requires --native-gateset")
        return get_target_for_gateset(native_gateset, qubits)

    return None


def generate_circuit(
    algorithm: str,
    level_name: str,
    qubits: int,
    opt_level: int,
    mirror: bool,
    random_parameters: bool,
    benchmark_level_enum,
    get_benchmark,
    get_device,
    get_target_for_gateset,
    mapped_target: Optional[str],
    native_gateset: Optional[str],
):
    level_enum_value = resolve_level(level_name, benchmark_level_enum)
    kwargs: Dict[str, object] = {
        "benchmark": algorithm,
        "level": level_enum_value,
        "circuit_size": qubits,
        "opt_level": opt_level,
        "generate_mirror_circuit": mirror,
        "random_parameters": random_parameters,
    }

    target = build_target_for_case(
        level_name,
        qubits,
        get_device,
        get_target_for_gateset,
        mapped_target,
        native_gateset,
    )
    if target is not None:
        kwargs["target"] = target

    return get_benchmark(**kwargs)


def analyze_circuit(
    case_id: str,
    algorithm: str,
    level: str,
    requested_qubits: int,
    circuit,
) -> Tuple[CaseResult, Optional[object]]:
    compressor = AdvancedTopologyCompressor(coupling_map=None)

    original_qubits = circuit.num_qubits
    original_depth = circuit.depth() or 0
    original_gates = len(circuit.data)

    with contextlib.redirect_stdout(io.StringIO()):
        compressed_circuit = compressor.compress_and_map(circuit)

    if compressed_circuit is None:
        return CaseResult(
            case_id=case_id,
            algorithm=algorithm,
            level=level,
            qubits=requested_qubits,
            status="error",
            detail="compress_and_map returned None",
            original_qubits=original_qubits,
            original_depth=original_depth,
            original_gates=original_gates,
        ), None

    compressed_qubits = compressed_circuit.num_qubits
    compressed_depth = compressed_circuit.depth() or 0
    compressed_gates = len(compressed_circuit.data)

    status = "compressed" if compressed_qubits < original_qubits else "not_compressed"
    detail = f"{original_qubits}->{compressed_qubits} qubits"

    return CaseResult(
        case_id=case_id,
        algorithm=algorithm,
        level=level,
        qubits=requested_qubits,
        status=status,
        detail=detail,
        original_qubits=original_qubits,
        compressed_qubits=compressed_qubits,
        original_depth=original_depth,
        compressed_depth=compressed_depth,
        original_gates=original_gates,
        compressed_gates=compressed_gates,
    ), compressed_circuit


def save_circuit_artifacts(
    output_dir: Path,
    case_id: str,
    circuit,
    kind: str,
    save_qcraft_python: bool,
) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    file_stem = sanitize_filename(f"{case_id}_{kind}")

    qasm_path = output_dir / f"{file_stem}.qasm"
    qpy_path = output_dir / f"{file_stem}.qpy"
    py_path = output_dir / f"{file_stem}.py"

    # Prefer QASM for readability, QPY for robust round-trip loading.
    qasm2_module = importlib.import_module("qiskit.qasm2")
    qasm_text = qasm2_module.dumps(circuit)
    qasm_path.write_text(qasm_text, encoding="utf-8")

    qpy_module = importlib.import_module("qiskit.qpy")
    with qpy_path.open("wb") as qpy_file:
        qpy_module.dump(circuit, qpy_file)

    if save_qcraft_python:
        py_source = _to_qcraft_python(circuit, case_id=f"{case_id}:{kind}")
        py_path.write_text(py_source, encoding="utf-8")

    return qasm_path


def run_benchmark(args: argparse.Namespace) -> List[CaseResult]:
    benchmark_level_enum, get_benchmark, get_device, get_target_for_gateset = load_mqt_bench_components()

    algorithms = parse_csv_items(args.algorithms)
    levels = parse_csv_items(args.levels)

    if not algorithms:
        raise RuntimeError("No algorithms provided")
    if not levels:
        raise RuntimeError("No levels provided")
    ensure_non_variational_algorithms(algorithms)

    qubit_values = list(range(args.min_qubits, args.max_qubits + 1, args.qubit_step))
    if not qubit_values:
        raise RuntimeError("No qubit sizes to process")

    total_cases = len(algorithms) * len(levels) * len(qubit_values)
    print("=" * 90)
    print("MQT BENCH LOCAL TOPOLOGY COMPRESSION TEST")
    print("=" * 90)
    print(f"Algorithms: {algorithms}")
    print(f"Levels: {levels}")
    print(f"Qubit sizes: {qubit_values}")
    print(f"Mirror: {args.mirror}")
    print(f"Random parameters: {args.random_parameters}")
    print(f"Opt level: {args.opt_level}")
    print(f"Total planned cases: {total_cases}")
    print(f"Output report: {args.output_file}")
    print(f"Save generated circuits: {args.save_generated} -> {args.generated_dir}")
    print(f"Save compressed circuits: {args.save_compressed}")
    print(f"Save qcraft python: {args.save_qcraft_python}")
    print()

    results: List[CaseResult] = []
    processed = 0

    for algorithm in algorithms:
        for level in levels:
            for qubits in qubit_values:
                if args.max_cases is not None and processed >= args.max_cases:
                    break

                processed += 1
                case_id = f"{algorithm}:{level}:{qubits}"

                try:
                    circuit = generate_circuit(
                        algorithm=algorithm,
                        level_name=level,
                        qubits=qubits,
                        opt_level=args.opt_level,
                        mirror=args.mirror,
                        random_parameters=args.random_parameters,
                        benchmark_level_enum=benchmark_level_enum,
                        get_benchmark=get_benchmark,
                        get_device=get_device,
                        get_target_for_gateset=get_target_for_gateset,
                        mapped_target=args.mapped_target,
                        native_gateset=args.native_gateset,
                    )
                    if args.save_generated:
                        save_circuit_artifacts(
                            Path(args.generated_dir),
                            case_id,
                            circuit,
                            "original",
                            save_qcraft_python=args.save_qcraft_python,
                        )

                    result, compressed_circuit = analyze_circuit(case_id, algorithm, level, qubits, circuit)

                    if args.save_compressed and compressed_circuit is not None:
                        save_circuit_artifacts(
                            Path(args.generated_dir),
                            case_id,
                            compressed_circuit,
                            "compressed",
                            save_qcraft_python=args.save_qcraft_python,
                        )
                except Exception as exc:
                    result = CaseResult(
                        case_id=case_id,
                        algorithm=algorithm,
                        level=level,
                        qubits=qubits,
                        status="error",
                        detail=str(exc)[:200],
                    )

                results.append(result)
                print(
                    f"[{len(results):03d}] {result.status:14s} {result.case_id:30s} - {result.detail}"
                )

            if args.max_cases is not None and processed >= args.max_cases:
                break
        if args.max_cases is not None and processed >= args.max_cases:
            break

    write_report(args.output_file, results, args)
    return results


def write_report(output_file: Path, results: List[CaseResult], args: argparse.Namespace) -> None:
    compressed = [r for r in results if r.status == "compressed"]
    not_compressed = [r for r in results if r.status == "not_compressed"]
    errors = [r for r in results if r.status == "error"]

    reduction_abs = [r.original_qubits - r.compressed_qubits for r in compressed]
    reduction_pct = [
        100.0 * (r.original_qubits - r.compressed_qubits) / r.original_qubits
        for r in compressed
        if r.original_qubits > 0
    ]

    lines: List[str] = []
    lines.append("=" * 90)
    lines.append("REPORT: MQT BENCH LOCAL TOPOLOGY COMPRESSION")
    lines.append("=" * 90)
    lines.append(f"Algorithms: {args.algorithms}")
    lines.append(f"Levels: {args.levels}")
    lines.append(
        f"Qubits: min={args.min_qubits}, max={args.max_qubits}, step={args.qubit_step}"
    )
    lines.append(f"Mirror: {args.mirror}")
    lines.append(f"Random parameters: {args.random_parameters}")
    lines.append(f"Opt level: {args.opt_level}")
    lines.append(f"Total cases: {len(results)}")
    lines.append(f"Compressed: {len(compressed)}")
    lines.append(f"Not compressed: {len(not_compressed)}")
    lines.append(f"Errors: {len(errors)}")

    if compressed:
        lines.append(f"Avg qubit reduction (abs): {mean(reduction_abs):.2f}")
        lines.append(f"Avg qubit reduction (%): {mean(reduction_pct):.2f}")

    lines.append("")
    lines.append("--- COMPRESSED ---")
    for r in compressed:
        lines.append(
            f"{r.case_id} | Q {r.original_qubits}->{r.compressed_qubits} | "
            f"D {r.original_depth}->{r.compressed_depth} | "
            f"G {r.original_gates}->{r.compressed_gates}"
        )

    lines.append("")
    lines.append("--- NOT COMPRESSED ---")
    for r in not_compressed:
        lines.append(
            f"{r.case_id} | Q {r.original_qubits}->{r.compressed_qubits} | "
            f"D {r.original_depth}->{r.compressed_depth} | "
            f"G {r.original_gates}->{r.compressed_gates}"
        )

    lines.append("")
    lines.append("--- ERRORS ---")
    for r in errors:
        lines.append(f"{r.case_id} | {r.detail}")

    output_file.write_text("\n".join(lines) + "\n", encoding="utf-8")


def parse_args() -> argparse.Namespace:
    default_output = Path(str(DEFAULT_CONFIG["output_file"]))

    parser = argparse.ArgumentParser(
        description="Generate MQT Bench circuits and test local topology compression"
    )
    parser.add_argument(
        "--algorithms",
        type=str,
        default=str(DEFAULT_CONFIG["algorithms"]),
        help="Comma-separated benchmark algorithms",
    )
    parser.add_argument(
        "--levels",
        type=str,
        default=str(DEFAULT_CONFIG["levels"]),
        help="Comma-separated levels: alg,indep,nativegates,mapped",
    )
    parser.add_argument("--min-qubits", type=int, default=int(DEFAULT_CONFIG["min_qubits"]), help="Minimum qubit count")
    parser.add_argument("--max-qubits", type=int, default=int(DEFAULT_CONFIG["max_qubits"]), help="Maximum qubit count")
    parser.add_argument("--qubit-step", type=int, default=int(DEFAULT_CONFIG["qubit_step"]), help="Step for qubit range")
    parser.add_argument("--opt-level", type=int, default=int(DEFAULT_CONFIG["opt_level"]), help="Transpiler optimization level")
    parser.add_argument("--mirror", action="store_true", help="Generate mirror circuits")
    parser.add_argument(
        "--random-parameters",
        action=argparse.BooleanOptionalAction,
        default=bool(DEFAULT_CONFIG["random_parameters"]),
        help="Use random values in parameterized circuits",
    )
    parser.add_argument(
        "--mapped-target",
        type=str,
        default=str(DEFAULT_CONFIG["mapped_target"]),
        help="Target for level=mapped",
    )
    parser.add_argument(
        "--native-gateset",
        type=str,
        default=str(DEFAULT_CONFIG["native_gateset"]),
        help="Gateset for level=nativegates",
    )
    parser.add_argument("--max-cases", type=int, default=DEFAULT_CONFIG["max_cases"], help="Limit total generated cases")
    parser.add_argument("--output-file", type=Path, default=default_output, help="Report output path")
    parser.add_argument(
        "--generated-dir",
        type=Path,
        default=Path(str(DEFAULT_CONFIG["generated_dir"])),
        help="Directory where generated circuits are saved (QASM and QPY)",
    )
    parser.add_argument(
        "--save-generated",
        action=argparse.BooleanOptionalAction,
        default=bool(DEFAULT_CONFIG["save_generated"]),
        help="Save generated circuits to disk",
    )
    parser.add_argument(
        "--save-compressed",
        action=argparse.BooleanOptionalAction,
        default=bool(DEFAULT_CONFIG["save_compressed"]),
        help="Save compressed circuits to disk",
    )
    parser.add_argument(
        "--save-qcraft-python",
        action=argparse.BooleanOptionalAction,
        default=bool(DEFAULT_CONFIG["save_qcraft_python"]),
        help="Save scheduler-friendly Python circuit files (.py)",
    )

    args = parser.parse_args()

    # Keep in-file defaults as the main workflow for quick reruns.
    if bool(DEFAULT_CONFIG["mirror"]):
        args.mirror = True

    return args


def main() -> None:
    args = parse_args()
    start = time.time()

    if args.min_qubits <= 0:
        raise ValueError("--min-qubits must be > 0")
    if args.max_qubits < args.min_qubits:
        raise ValueError("--max-qubits must be >= --min-qubits")
    if args.qubit_step <= 0:
        raise ValueError("--qubit-step must be > 0")

    results = run_benchmark(args)

    compressed = sum(1 for r in results if r.status == "compressed")
    not_compressed = sum(1 for r in results if r.status == "not_compressed")
    errors = sum(1 for r in results if r.status == "error")

    print("\n" + "=" * 90)
    print("SUMMARY")
    print("=" * 90)
    print(f"Compressed:      {compressed}")
    print(f"Not compressed:  {not_compressed}")
    print(f"Errors:          {errors}")
    print(f"Total:           {len(results)}")
    print(f"Elapsed seconds: {time.time() - start:.2f}")


if __name__ == "__main__":
    main()
