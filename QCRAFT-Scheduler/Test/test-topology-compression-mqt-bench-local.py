#   - modular_adder: must be EVEN (e.g., 2, 4, 6, 8, 10)
#   - shor: ONLY specific sizes (18, 42, 58, 74)
#   - Others: No size restrictions
# Recommended: 8 or 10 qubits for most algorithms without errors.

